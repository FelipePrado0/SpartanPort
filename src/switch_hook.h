/* The stub, then jmp [rip] back to the game after the replaced bytes. */
static inline unsigned spartanport_switch_build_stub(unsigned char *out, const SpartanSwitchSite *site, uintptr_t state,
                                              uintptr_t call, uintptr_t pass, uintptr_t resume) {
    static const unsigned char jump[] = {0xff,0x25,0,0,0,0}; /* jmp [rip+0] */
    memcpy(out, site->stub, site->stub_length);
    if (site->state_at >= 0) memcpy(out + site->state_at, &state, 8);
    if (site->call_at >= 0) memcpy(out + site->call_at, &call, 8);
    if (site->pass_at >= 0) memcpy(out + site->pass_at, &pass, 8);
    memcpy(out + site->stub_length, jump, sizeof(jump));
    memcpy(out + site->stub_length + sizeof(jump), &resume, 8);
    return site->stub_length + sizeof(jump) + 8;
}

/* A branch to a weapon's switch attack, as the game's data has them all. */
static inline int spartanport_switch_branch(const unsigned char *b) {
    return b[0x30] == 1 && (b[0x31] == 1 || b[0x31] == 4) && b[0x2e] == 0x0f && b[0x2f] >= 0x10 && b[0x2f] <= 0x13 &&
           b[0x2c] == 0xff && b[0x2d] == 0xff && b[0x10] == 0xaa && b[0x11] == 0xaa;
}
