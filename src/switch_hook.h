/* Switch attacks (runtime_pad.c, SPARTAN_SWITCH_ATTACKS). Offsets as found in a v01.02 build; builds
 * are found by signature.
 *
 * Kratos' moves change through branches: a branch names the move it goes to (rel32 at +0x00),
 * the input that takes it (+0x30 input, 1 = the button 0x40, Cross; +0x31 how, 1 = just pressed,
 * 4 = held) and the item it is for (+0x2f). A weapon's switch attack is a move of its own (two of them: one
 * for most moves, one for a few others), reached from the block moves by branches for Cross just
 * pressed (and, in a few moves, Cross held), item 0x10 Nemean Cestus, 0x11 Nemesis Whip, 0x12 Blades of Exile or 0x13 Claws of
 * Hades. A block move only has branches to the weapons that follow in the game's cycle; the
 * switch attack's script selects its weapon (SCR_EnableWeapon).
 *
 * Three hooks:
 * - input check (0xeb290, rdx the branch): a branch to a switch attack is taken by the pad's
 *   request (spartanport_switch_input) instead of Cross; the move's other conditions stay the game's.
 *   Only from 0xe3910, the move's branches for the input queue; from the other caller (0xe9a70)
 *   they are never taken, or Cross would still cycle the weapons there;
 * - input queue (0xe4063 in 0xe3910, rax the branch the move chose): the branch is swapped for
 *   one of the game's branches to the requested weapon's switch attack, the same kind
 *   (spartanport_switch_queue);
 * - d-pad weapon select (0x6b240, rdi his player stats): notes the stats.
 * The stubs are assembled from tools/switch_stubs.s. */
enum { SPARTAN_SWITCH_SITES = 3, SPARTAN_SWITCH_SLOT = 512 };

/* Shared with the stubs. */
typedef struct {
    uint64_t caller;  /* the input check's return into 0xe3910, the only caller it answers */
    uint64_t stats;   /* +8: his player stats, from the d-pad select */
} SpartanSwitchState;
#ifdef __cplusplus
static_assert(offsetof(SpartanSwitchState, stats) == 8, "the stub writes the stats at +8");
#else
_Static_assert(offsetof(SpartanSwitchState, stats) == 8, "the stub writes the stats at +8");
#endif

