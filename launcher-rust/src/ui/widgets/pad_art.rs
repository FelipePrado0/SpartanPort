//! Generated from the controllers in `assets/pads` (see its LICENSE.txt): the picture of each
//! controller and, for each input, the mask that lights it and where that mask sits.

/// One input of a controller picture, in the picture's pixels.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ArtPart {
    pub id: &'static str,
    pub cap: &'static str,
    pub x: u32,
    pub y: u32,
    pub w: u32,
    pub h: u32,
    pub mask: &'static [u8],
}

/// A controller picture.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Art {
    pub width: u32,
    pub height: u32,
    pub base: &'static [u8],
    pub parts: &'static [ArtPart],
}

