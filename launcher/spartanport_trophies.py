def text(language, trophy):
    """(name, description) of a trophy id in a launcher language; English when the language has none."""
    texts = TEXTS.get(language) or TEXTS['en']
    if not 0 <= trophy < len(texts):
        return ('', '')
    return texts[trophy]


def read_trp_icons(path):
    """{trophy id: PNG bytes} from the game's sce_sys/trophy/trophy00.trp ({} when missing or odd).

    The package header is big endian: magic DC A2 4D 00, file count at 0x10, entry size at 0x14;
    the entries start at 0x60 (32-byte name, offset, size). The icons are TROP000.PNG, TROP001.PNG...
    The texts (TROP*.ESFM) are encrypted and not read here."""
    try:
        data = Path(path).read_bytes()
    except OSError:
        return {}
    if len(data) < 0x60 or data[:4] != b'\xdc\xa2\x4d\x00':
        return {}
    count, element = struct.unpack('>II', data[0x10:0x18])
    if not 0x30 <= element <= 0x100:
        return {}
    icons = {}
    for index in range(min(count, 4096)):
        start = 0x60 + index * element
        entry = data[start:start + 0x30]
        if len(entry) < 0x30:
            break
        name = entry[:0x20].split(b'\0')[0].decode('ascii', 'replace')
        match = re.fullmatch(r'TROP(\d{3})\.PNG', name)
        if not match:
            continue
        offset, size = struct.unpack('>QQ', entry[0x20:0x30])
        if size and offset + size <= len(data):
            icons[int(match.group(1))] = data[offset:offset + size]
    return icons


def read_unlocked_trophies(path):
    """The trophy ids the port recorded: user/trophies.dat holds four little-endian 32-bit flag words."""
    try:
        raw = Path(path).read_bytes()[:16]
    except OSError:
        return set()
    flags = struct.unpack('<4I', raw.ljust(16, b'\0'))
    return {i for i in range(128) if flags[i // 32] >> (i % 32) & 1}


def trophy_tier(png):
    """'platinum', 'gold', 'silver' or 'bronze' by the colour of the icon; '' without Pillow."""
    try:
        from PIL import Image
        raw = Image.open(io.BytesIO(png)).convert('RGB').resize((24, 24)).tobytes()
    except (ImportError, OSError):
        return ''
    pixels = [raw[i:i + 3] for i in range(0, len(raw), 3) if max(raw[i:i + 3]) > 60]
    if not pixels:
        return ''
    r, g, b = (sum(p[c] for p in pixels) / len(pixels) for c in range(3))
    spread = (max(r, g, b) - min(r, g, b)) / max(r, g, b)
    if b >= r:
        return 'platinum'
    return 'silver' if spread < 0.4 else 'bronze' if spread < 0.72 else 'gold'


def reset_trophies(path):
    """Locks every trophy again: user/trophies.dat is moved to trophies.dat.bak (replacing an older
    copy). Returns how many trophies were unlocked (0: nothing is changed); OSError when the file
    cannot be moved. The game must be closed: it keeps the trophies in memory while it runs."""
    path = Path(path)
    unlocked = len(read_unlocked_trophies(path))
    if unlocked:
        os.replace(path, path.with_name(path.name + '.bak'))
    return unlocked
